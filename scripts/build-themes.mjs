/**
 * Build-time asset embedding & pre-rendered gallery SVGs.
 *
 * Reads every theme folder under `src/assets/<theme>/` (digits 0-9 as PNG or GIF),
 * parses each image's real dimensions, writes:
 *  - `src/generated/themes.ts`  -> runtime base64 assets
 *  - `src/generated/gallery.ts` -> pre-rendered static 0-9 showcase SVGs
 *
 * Result: zero runtime I/O, zero gallery render cost, and immutable browser caching.
 */
import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const __dirname = path.dirname(fileURLToPath(import.meta.url));
const assetsDir = path.join(__dirname, '../src/assets');
const outDir = path.join(__dirname, '../src/generated');
const themesOutFile = path.join(outDir, 'themes.ts');
const galleryOutFile = path.join(outDir, 'gallery.ts');

const MIME = { png: 'image/png', gif: 'image/gif' };

function parseDimensions(buf, file) {
  if (buf.length >= 24 && buf[0] === 0x89 && buf[1] === 0x50 && buf[2] === 0x4e && buf[3] === 0x47) {
    return { width: buf.readUInt32BE(16), height: buf.readUInt32BE(20) };
  }
  if (buf.length >= 10 && buf[0] === 0x47 && buf[1] === 0x49 && buf[2] === 0x46) {
    return { width: buf.readUInt16LE(6), height: buf.readUInt16LE(8) };
  }
  throw new Error(`Unsupported image format: ${file}`);
}

const themes = {};
const gallerySvgs = {};

const themeNames = fs
  .readdirSync(assetsDir)
  .filter((name) => fs.statSync(path.join(assetsDir, name)).isDirectory())
  .sort();

for (const theme of themeNames) {
  if (!/^[a-z0-9_-]+$/.test(theme)) {
    throw new Error(`Invalid theme folder name "${theme}" (allowed: a-z, 0-9, _ and -)`);
  }

  const digits = [];
  for (let d = 0; d <= 9; d++) {
    const ext = ['png', 'gif'].find((e) => fs.existsSync(path.join(assetsDir, theme, `${d}.${e}`)));
    if (!ext) {
      throw new Error(`Theme "${theme}" is missing digit ${d} (expected ${d}.png or ${d}.gif)`);
    }
    const file = path.join(assetsDir, theme, `${d}.${ext}`);
    const buf = fs.readFileSync(file);
    const { width, height } = parseDimensions(buf, file);
    digits.push({ width, height, href: `data:${MIME[ext]};base64,${buf.toString('base64')}` });
  }

  const maxHeight = Math.max(...digits.map((d) => d.height));
  themes[theme] = { height: maxHeight, digits };

  // Pre-render the 0-9 showcase strip SVG at build time
  let defs = '';
  let uses = '';
  let x = 0;
  for (let d = 0; d <= 9; d++) {
    const asset = digits[d];
    defs += `<image id="d${d}" width="${asset.width}" height="${asset.height}" href="${asset.href}" style="image-rendering:pixelated"/>`;
    uses += `<use href="#d${d}" x="${x}"/>`;
    x += asset.width;
  }
  gallerySvgs[theme] = `<svg width="${x}" height="${maxHeight}" viewBox="0 0 ${x} ${maxHeight}" xmlns="http://www.w3.org/2000/svg"><defs>${defs}</defs><g>${uses}</g></svg>`;
}

const themesSource = `// AUTO-GENERATED by scripts/build-themes.mjs — DO NOT EDIT.
// Regenerate with: npm run build:themes

export interface DigitAsset {
  width: number;
  height: number;
  href: string;
}

export interface ThemeAsset {
  height: number;
  digits: DigitAsset[];
}

export const THEMES: Record<string, ThemeAsset> = ${JSON.stringify(themes)};
`;

const gallerySource = `// AUTO-GENERATED by scripts/build-themes.mjs — DO NOT EDIT.
// Pre-rendered 0-9 gallery showcase SVGs are generated lazily once per isolate
// from THEMES so the Worker bundle stays well under Cloudflare's 3 MB Free limit.
import { THEMES } from './themes.js';

const cache = new Map<string, string>();

export function getGallerySVG(theme: string): string | undefined {
  const cached = cache.get(theme);
  if (cached) return cached;

  const asset = THEMES[theme];
  if (!asset) return undefined;

  let defs = '';
  let uses = '';
  let x = 0;
  for (let d = 0; d <= 9; d++) {
    const digit = asset.digits[d];
    defs += \`<image id="d\${d}" width="\${digit.width}" height="\${digit.height}" href="\${digit.href}" style="image-rendering:pixelated"/>\`;
    uses += \`<use href="#d\${d}" x="\${x}"/>\`;
    x += digit.width;
  }
  const svg = \`<svg width="\${x}" height="\${asset.height}" viewBox="0 0 \${x} \${asset.height}" xmlns="http://www.w3.org/2000/svg"><defs>\${defs}</defs><g>\${uses}</g></svg>\`;
  cache.set(theme, svg);
  return svg;
}
`;

const sakuraPngPath = path.join(__dirname, '../src/assets/SakuraBG.png');
const sakuraDataUri = fs.existsSync(sakuraPngPath)
  ? 'data:image/png;base64,' + fs.readFileSync(sakuraPngPath).toString('base64')
  : '';
const decorSource = `// AUTO-GENERATED by scripts/build-themes.mjs — DO NOT EDIT.
export const SAKURA_BG_DATA_URI = ${JSON.stringify(sakuraDataUri)};
`;

fs.mkdirSync(outDir, { recursive: true });
fs.writeFileSync(themesOutFile, themesSource);
fs.writeFileSync(galleryOutFile, gallerySource);
fs.writeFileSync(path.join(outDir, 'decor.ts'), decorSource);

// Save static gallery SVGs to assets/gallery for direct GitHub README preview
const galleryAssetsDir = path.join(__dirname, '../assets/gallery');
fs.mkdirSync(galleryAssetsDir, { recursive: true });
for (const [theme, svg] of Object.entries(gallerySvgs)) {
  fs.writeFileSync(path.join(galleryAssetsDir, `${theme}.svg`), svg);
}

const kb = (Buffer.byteLength(themesSource) / 1024).toFixed(0);
console.log(`✅ Embedded ${themeNames.length} themes, pre-rendered gallery SVGs & exported to assets/gallery/ (${kb} KB)`);
